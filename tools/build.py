"""Deterministic, dependency-free UEVR profile build. No game access."""
from pathlib import Path
import argparse
import hashlib
import json
import zipfile

ROOT = Path(__file__).resolve().parents[1]
MODULES = [
    ('IK', 'ik_math.lua'), ('Motion', 'motion.lua'), ('Rate', 'shake_rate.lua'),
    ('Gestures', 'gestures.lua'), ('Calibration', 'calibration.lua'),
    ('Visuals', 'visuals.lua'), ('Pointer', 'pointer.lua'), ('HUD', 'hud.lua'),
    ('Turning', 'turning.lua'), ('Squeeze', 'squeeze.lua'), ('Rendering', 'rendering.lua'),
]
PROFILE = [
    'config.txt', '_interaction_profiles_oculus_touch_controller.json',
    '_interaction_profiles_valve_index_controller.json', 'scripts/main.lua',
]
ARCHIVE = 'Ratshaker-Win64-Shipping.zip'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def source_bytes(path):
    return path.read_text(encoding='utf-8').replace('\r\n', '\n').encode('utf-8')


def entry():
    version = (ROOT / 'VERSION').read_text(encoding='utf-8').strip()
    inputs = [(name, sha(source_bytes(ROOT / 'src' / name))) for _, name in MODULES]
    inputs.append(('runtime.lua', sha(source_bytes(ROOT / 'src/runtime.lua'))))
    inputs += [(name, sha(source_bytes(ROOT / 'profile' / name))) for name in PROFILE if name != 'scripts/main.lua']
    build_id = sha(json.dumps([version, inputs], separators=(',', ':')).encode())
    chunks = [
        '-- Generated by tools/build.py. Edit src/, then rebuild. MIT; see LICENSE.\n',
        'if rawget(_G,"RATSHAKER_VR_MOD_ACTIVE") then return end\n',
        'rawset(_G,"RATSHAKER_VR_MOD_ACTIVE",true)\n',
        f'local RATSHAKER_VR_BUILD_ID="{build_id}"\n',
        f'local RATSHAKER_VR_VERSION={json.dumps(version)}\n',
    ]
    for variable, name in MODULES:
        chunks.append(f'local {variable}=(function()\n' + source_bytes(ROOT / 'src' / name).decode() + '\nend)()\n')
    chunks.append(source_bytes(ROOT / 'src/runtime.lua').decode())
    return '\n'.join(chunks).encode('utf-8')


def release_files():
    files = {name: source_bytes(ROOT / 'profile' / name) for name in PROFILE}
    files.update({name: source_bytes(ROOT / name) for name in ['LICENSE', 'NOTICE.md']})
    return files


def archive_bytes(files):
    import io
    output = io.BytesIO()
    with zipfile.ZipFile(output, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, data)
    return output.getvalue()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check generated entry without writing files')
    args = parser.parse_args()
    generated = entry()
    target = ROOT / 'profile/scripts/main.lua'
    if args.check:
        if not target.exists() or source_bytes(target) != generated:
            raise SystemExit('Generated profile is stale. Run npm run build and commit profile/scripts/main.lua.')
        print('Generated entry matches source: ' + sha(generated))
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(generated)
    dist = ROOT / 'dist'
    dist.mkdir(exist_ok=True)
    payload = archive_bytes(release_files())
    (dist / ARCHIVE).write_bytes(payload)
    (dist / 'SHA256SUMS.txt').write_text(sha(payload) + '  ' + ARCHIVE + '\n', encoding='utf-8', newline='\n')
    print(f'Built dist/{ARCHIVE} ({len(payload)} bytes); entry SHA256 {sha(generated)}')


if __name__ == '__main__':
    main()
